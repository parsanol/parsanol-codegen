//! PARG → Rust source code generation (the compiled-backend frontier).
//!
//! The honest seven-tool benchmark has tree-sitter/pest parsing the same
//! document ~60x faster than the interpreted walker: interpretation has a
//! ceiling, and the way past it is codegen — compile the grammar to plain
//! Rust the way pest compiles to a proc-macro parser.
//!
//! **POC scope (v0.1, acceptance subset):** `Str`, `Sequence`,
//! `Alternative`, `Repetition`, `Named`/`Entity` (transparent). The
//! generated module exposes `parse(input) -> Option<usize>` —
//! full-consumption acceptance with the end offset, PEG semantics
//! (ordered choice with backtracking, greedy repetition with the
//! zero-progress guard) identical to the walker's.
//!
//! Everything else — regex terminals, captures and the flatten laws,
//! predicates, trivia, lookarounds, the tree itself — is deliberately
//! unsupported until its milestone (docs/tickets/0001-roadmap.md).
//! Unsupported means `Err(CodegenError::Unsupported)`, never wrong code.

use parsanol::portable::grammar::{Atom, Grammar};
use std::fmt;

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CodegenError {
    Unsupported(&'static str),
}

impl fmt::Display for CodegenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            CodegenError::Unsupported(what) => {
                write!(f, "codegen POC does not support {what} yet")
            }
        }
    }
}

impl std::error::Error for CodegenError {}

/// Generate a standalone Rust module exposing
/// `parse(input: &str) -> Option<usize>` — full-consumption acceptance
/// with the end offset.
pub fn generate_acceptance(grammar: &Grammar) -> Result<String, CodegenError> {
    let mut out = String::from(
        "// Generated by parsanol-codegen — do not edit.\n\
         // PEG semantics: ordered choice, greedy repetition, full consumption.\n\n\
         pub fn parse(input: &str) -> Option<usize> {\n\
         \x20   let end = p",
    );
    out.push_str(&grammar.root.to_string());
    out.push_str("(input, 0)?;\n");
    out.push_str("    if end == input.len() { Some(end) } else { None }\n}\n\n");
    let mut emitter = Emitter {
        out,
        emitted: std::collections::HashSet::new(),
    };
    emitter.emit_atom(grammar, grammar.root)?;
    Ok(emitter.out)
}

struct Emitter {
    out: String,
    emitted: std::collections::HashSet<usize>,
}

impl Emitter {
    fn fn_name(&self, atom_id: usize) -> String {
        format!("p{atom_id}")
    }

    fn emit_atom(&mut self, grammar: &Grammar, atom_id: usize) -> Result<(), CodegenError> {
        let name = self.fn_name(atom_id);
        // Grammars are a DAG, not a tree: compacted grammars share child
        // atoms between parents. Emit each atom exactly once.
        if !self.emitted.insert(atom_id) {
            return Ok(());
        }
        let atom = grammar
            .get_atom(atom_id)
            .ok_or(CodegenError::Unsupported("atom index out of range"))?;
        match atom {
            Atom::Str { pattern } => {
                let bytes: Vec<String> = pattern.as_bytes().iter().map(|b| b.to_string()).collect();
                self.out.push_str(&format!(
                    "const B{atom_id}: &[u8] = &[{}];\n",
                    bytes.join(", ")
                ));
                self.out.push_str(&format!(
                    "fn {name}(s: &str, pos: usize) -> Option<usize> {{\n\
                     \x20   let b = s.as_bytes();\n\
                     \x20   let pat = B{atom_id};\n\
                     \x20   if b.get(pos..)?.starts_with(pat) {{ Some(pos + pat.len()) }} else {{ None }}\n\
                     }}\n\n"
                ));
                Ok(())
            }
            Atom::Sequence { atoms } => {
                self.out.push_str(&format!(
                    "fn {name}(s: &str, pos: usize) -> Option<usize> {{\n    let mut p = pos;\n"
                ));
                for child in atoms {
                    self.out
                        .push_str(&format!("    p = {}(s, p)?;\n", self.fn_name(*child)));
                }
                self.out.push_str("    Some(p)\n}\n\n");
                for child in atoms {
                    self.emit_atom(grammar, *child)?;
                }
                Ok(())
            }
            Atom::Alternative { atoms } => {
                let mut chain = String::new();
                for (index, child) in atoms.iter().enumerate() {
                    if index == 0 {
                        chain.push_str(&format!("{}(s, pos)", self.fn_name(*child)));
                    } else {
                        chain.push_str(&format!(".or_else(|| {}(s, pos))", self.fn_name(*child)));
                    }
                }
                self.out.push_str(&format!(
                    "fn {name}(s: &str, pos: usize) -> Option<usize> {{\n    {chain}\n}}\n\n"
                ));
                for child in atoms {
                    self.emit_atom(grammar, *child)?;
                }
                Ok(())
            }
            Atom::Repetition { atom, min, max, .. } => {
                let max_check = match max {
                    Some(max) => format!("if count >= {max} {{ break; }}"),
                    None => String::new(),
                };
                self.out.push_str(&format!(
                    "fn {name}(s: &str, pos: usize) -> Option<usize> {{\n\
                     \x20   let mut p = pos;\n\
                     \x20   let mut count = 0usize;\n\
                     \x20   loop {{\n\
                     \x20       {max_check}\n\
                     \x20       match {}(s, p) {{\n\
                     \x20           Some(next) if next > p => {{ p = next; count += 1; }}\n\
                     \x20           Some(next) => {{ p = next; count += 1; break; }}\n\
                     \x20           None => break,\n\
                     \x20       }}\n\
                     \x20   }}\n\
                     \x20   if count >= {min} {{ Some(p) }} else {{ None }}\n\
                     }}\n\n",
                    self.fn_name(*atom)
                ));
                self.emit_atom(grammar, *atom)
            }
            Atom::Named { atom, .. } | Atom::Entity { atom } => {
                self.out.push_str(&format!(
                    "fn {name}(s: &str, pos: usize) -> Option<usize> {{\n    {}(s, pos)\n}}\n\n",
                    self.fn_name(*atom)
                ));
                self.emit_atom(grammar, *atom)
            }
            other => {
                let _ = other;
                Err(CodegenError::Unsupported(
                    "this atom kind (POC covers Str/Sequence/Alternative/Repetition/Named/Entity)",
                ))
            }
        }
    }
}
