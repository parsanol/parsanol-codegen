//! PARG → Rust source code generation (the compiled-backend frontier).
//!
//! The honest seven-tool benchmark has tree-sitter/pest parsing the same
//! document ~60x faster than the interpreted walker: interpretation has a
//! ceiling, and the way past it is codegen — compile the grammar to plain
//! Rust the way pest compiles to a proc-macro parser.
//!
//! Two generation modes:
//!
//! - **Acceptance** (`generate_acceptance`): `parse(input) -> Option<usize>`
//!   — full-consumption acceptance with the end offset.
//! - **Shape** (`generate_shape`): `parse_shape(input) -> Option<String>` —
//!   the canonical flattened value tree (V0–V4: values, captures, the
//!   sequence-merge laws with the FLAT map/array append, and the
//!   named-context rule — a capture's direct value only), rendered as a
//!   canonical s-expression for differential comparison.
//!
//! POC subset: `Str`, class-subset `Re`, `Sequence`, `Alternative`,
//! `Repetition`, `Named`/`Entity`. Everything else is
//! `Err(CodegenError::Unsupported)` — never wrong code.

use parsanol::portable::char_class::CharacterPattern;
use parsanol::portable::grammar::{Atom, Grammar, RepetitionTag};
use std::fmt;

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Mode {
    Acceptance,
    Shape,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum CodegenError {
    Unsupported(&'static str),
}

impl fmt::Display for CodegenError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            CodegenError::Unsupported(what) => {
                write!(f, "codegen POC does not support {what} yet")
            }
        }
    }
}

impl std::error::Error for CodegenError {}

/// Generate a standalone module in the given mode.
pub fn generate(grammar: &Grammar, mode: Mode) -> Result<String, CodegenError> {
    let mut emitter = Emitter {
        out: String::new(),
        emitted: std::collections::HashSet::new(),
        helpers: std::collections::HashSet::new(),
        mode,
    };
    emitter.emit_atom(grammar, grammar.root)?;

    let mut out = String::new();
    out.push_str("// Generated by parsanol-codegen — do not edit.\n");
    match mode {
        Mode::Acceptance => {
            out.push_str(
                "// PEG semantics: ordered choice, greedy repetition, full consumption.\n\n\
                 pub fn parse(input: &str) -> Option<usize> {\n\
                 \x20   let end = p",
            );
            out.push_str(&grammar.root.to_string());
            out.push_str("(input, 0)?;\n");
            out.push_str("    if end == input.len() { Some(end) } else { None }\n}\n\n");
        }
        Mode::Shape => {
            out.push_str(SHAPE_RUNTIME);
            out.push_str(
                "\npub fn parse_shape(input: &str) -> Option<String> {\n    let end_r = p",
            );
            out.push_str(&grammar.root.to_string());
            out.push_str(
                "(input, 0)?;\n    let (end, raw) = end_r;\n\
                 \x20   if end != input.len() { return None; }\n\
                 \x20   Some(render(&flatten_value(raw, false)))\n}\n\n",
            );
        }
    }
    out.push_str(&emitter.out);
    Ok(out)
}

/// Acceptance module: `parse(input: &str) -> Option<usize>`.
pub fn generate_acceptance(grammar: &Grammar) -> Result<String, CodegenError> {
    generate(grammar, Mode::Acceptance)
}

/// Shape module: `parse_shape(input: &str) -> Option<String>` (canonical
/// s-expression of the flattened value tree).
pub fn generate_shape(grammar: &Grammar) -> Result<String, CodegenError> {
    generate(grammar, Mode::Shape)
}

/// The value domain and the flatten laws (V0–V4), emitted into every shape
/// module. The merge laws are the parslet `CanFlatten` contract including
/// the FLAT map/array append; the named context applies to a capture's
/// direct value only (a sequence resets it).
const SHAPE_RUNTIME: &str = r#"
#[derive(Clone, Debug, PartialEq)]
enum Value {
    Nil,
    Text(String),
    Map(Vec<(String, Value)>),
    Seq(Vec<Value>),
    Rep(Vec<Value>),
    Maybe(Vec<Value>),
}

fn merge_values(left: Value, right: Value) -> Value {
    match (&left, &right) {
        (Value::Nil, r) => r.clone(),
        (l, Value::Nil) => l.clone(),
        (Value::Text(a), Value::Text(b)) => Value::Text(format!("{a}{b}")),
        (Value::Text(_), r) => r.clone(),
        (l, Value::Text(_)) => l.clone(),
        (Value::Map(a), Value::Map(b)) => {
            let mut merged: Vec<(String, Value)> = a.clone();
            for (key, value) in b {
                if let Some(slot) = merged.iter_mut().find(|(k, _)| k == key) {
                    slot.1 = value.clone(); // the right value wins
                } else {
                    merged.push((key.clone(), value.clone()));
                }
            }
            Value::Map(merged)
        }
        (Value::Seq(a), Value::Seq(b)) => {
            let mut out = a.clone();
            out.extend(b.clone());
            Value::Seq(out)
        }
        (l, Value::Map(pairs)) => {
            // H ++ A: a map beside an array appends FLAT.
            let mut out = vec![l.clone()];
            out.extend(
                pairs
                    .iter()
                    .map(|(k, v)| Value::Map(vec![(k.clone(), v.clone())])),
            );
            Value::Seq(out)
        }
        (Value::Map(pairs), r) => {
            let mut out = vec![Value::Map(pairs.clone())];
            if let Value::Seq(items) = r {
                out.extend(items.iter().cloned());
            } else {
                out.push(r.clone());
            }
            Value::Seq(out)
        }
        // Unreachable after flattening (Rep/Maybe resolve in
        // flatten_value); mirrors the B2 fallback: wrap both sides.
        _ => Value::Seq(vec![left.clone(), right.clone()]),
    }
}

fn flatten_value(value: Value, in_capture: bool) -> Value {
    match value {
        Value::Nil => Value::Nil,
        Value::Text(t) => Value::Text(t),
        // A map is a CAPTURE BOUNDARY (V4): its direct values use the
        // named context; sequences below them reset it.
        Value::Map(pairs) => Value::Map(
            pairs
                .into_iter()
                .map(|(k, v)| (k, flatten_value(v, true)))
                .collect(),
        ),
        Value::Seq(items) => {
            // A sequence never carries the named context to its children.
            let mut merged: Option<Value> = None;
            for item in items {
                let flat = flatten_value(item, false);
                merged = Some(match merged {
                    None => flat,
                    Some(left) => merge_values(left, flat),
                });
            }
            match merged {
                None => Value::Text(String::new()), // an empty sequence is ""
                Some(v) => v,
            }
        }
        Value::Rep(items) => {
            if items.is_empty() {
                // V3 rule 3: an empty repetition yields [] only directly
                // inside a capture; otherwise "".
                return if in_capture {
                    Value::Seq(vec![])
                } else {
                    Value::Text(String::new())
                };
            }
            let flattened: Vec<Value> = items
                .into_iter()
                .map(|item| flatten_value(item, in_capture))
                .collect();
            // V3 rule 1: maps win — keep exactly the map iterations.
            if flattened.iter().any(|item| matches!(item, Value::Map(_))) {
                return Value::Seq(
                    flattened
                        .into_iter()
                        .filter(|item| matches!(item, Value::Map(_)))
                        .collect(),
                );
            }
            // V3 rule 2: arrays next — concatenate the array iterations.
            if flattened.iter().any(|item| matches!(item, Value::Seq(_))) {
                let mut out: Vec<Value> = Vec::new();
                for item in flattened {
                    if let Value::Seq(mut inner) = item {
                        out.append(&mut inner);
                    }
                }
                return Value::Seq(out);
            }
            // V3 rule 4: all-text runs concatenate.
            let mut text = String::new();
            for item in flattened {
                if let Value::Text(t) = item {
                    text.push_str(&t);
                }
            }
            Value::Text(text)
        }
        Value::Maybe(items) => match items.into_iter().next() {
            Some(inner) => {
                let flat = flatten_value(inner, in_capture);
                if in_capture {
                    flat
                } else if matches!(flat, Value::Nil) {
                    Value::Text(String::new())
                } else {
                    flat
                }
            }
            None => {
                if in_capture {
                    Value::Nil
                } else {
                    Value::Text(String::new())
                }
            }
        },
    }
}

fn escape_text(text: &str) -> String {
    let mut out = String::new();
    for c in text.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            other => out.push(other),
        }
    }
    out
}

fn render(value: &Value) -> String {
    match value {
        Value::Nil => "(nil)".to_string(),
        Value::Text(t) => format!("(text \"{}\")", escape_text(t)),
        Value::Map(pairs) => {
            let mut sorted: Vec<&(String, Value)> = pairs.iter().collect();
            sorted.sort_by(|a, b| a.0.cmp(&b.0));
            let mut out = String::from("(map");
            for (key, item) in sorted {
                out.push_str(&format!(" (k \"{}\" {})", escape_text(key), render(item)));
            }
            out.push(')');
            out
        }
        Value::Seq(items) => {
            let mut out = String::from("(seq");
            for item in items {
                out.push(' ');
                out.push_str(&render(item));
            }
            out.push(')');
            out
        }
        Value::Rep(items) => {
            let mut out = String::from("(rep");
            for item in items {
                out.push(' ');
                out.push_str(&render(item));
            }
            out.push(')');
            out
        }
        Value::Maybe(items) => {
            let mut out = String::from("(maybe");
            for item in items {
                out.push(' ');
                out.push_str(&render(item));
            }
            out.push(')');
            out
        }
    }
}
"#;

struct Emitter {
    out: String,
    emitted: std::collections::HashSet<usize>,
    helpers: std::collections::HashSet<&'static str>,
    mode: Mode,
}

impl Emitter {
    fn fn_name(&self, atom_id: usize) -> String {
        format!("p{atom_id}")
    }

    fn emit_atom(&mut self, grammar: &Grammar, atom_id: usize) -> Result<(), CodegenError> {
        let name = self.fn_name(atom_id);
        // Grammars are a DAG, not a tree: compacted grammars share child
        // atoms between parents. Emit each atom exactly once.
        if !self.emitted.insert(atom_id) {
            return Ok(());
        }
        let atom = grammar
            .get_atom(atom_id)
            .ok_or(CodegenError::Unsupported("atom index out of range"))?;
        match atom {
            Atom::Str { pattern } => {
                let bytes: Vec<String> = pattern.as_bytes().iter().map(|b| b.to_string()).collect();
                self.out.push_str(&format!(
                    "const B{atom_id}: &[u8] = &[{}];\n",
                    bytes.join(", ")
                ));
                if self.mode == Mode::Shape {
                    let escaped = pattern.escape_default().to_string();
                    self.out
                        .push_str(&format!("const S{atom_id}: &str = \"{escaped}\";\n"));
                }
                let ret = match self.mode {
                    Mode::Acceptance => "Some(pos + pat.len())".to_string(),
                    Mode::Shape => {
                        format!("Some((pos + pat.len(), Value::Text(S{atom_id}.to_string())))")
                    }
                };
                self.out.push_str(&format!(
                    "fn {name}(s: &str, pos: usize) -> Option<{}> {{\n\
                     \x20   let b = s.as_bytes();\n\
                     \x20   let pat = B{atom_id};\n\
                     \x20   if b.get(pos..)?.starts_with(pat) {{ {} }} else {{ None }}\n\
                     }}\n\n",
                    match self.mode {
                        Mode::Acceptance => "usize",
                        Mode::Shape => "(usize, Value)",
                    },
                    ret
                ));
                Ok(())
            }
            Atom::Re { pattern } => self.emit_re(atom_id, pattern),
            Atom::Sequence { atoms } => {
                let ret_type = match self.mode {
                    Mode::Acceptance => "usize",
                    Mode::Shape => "(usize, Value)",
                };
                self.out.push_str(&format!(
                    "fn {name}(s: &str, pos: usize) -> Option<{ret_type}> {{\n    let mut p = pos;\n"
                ));
                if self.mode == Mode::Shape {
                    self.out
                        .push_str("    let mut items: Vec<Value> = Vec::new();\n");
                }
                for child in atoms {
                    match self.mode {
                        Mode::Acceptance => {
                            self.out
                                .push_str(&format!("    p = {}(s, p)?;\n", self.fn_name(*child)));
                        }
                        Mode::Shape => {
                            self.out.push_str(&format!(
                                "    let (next, value) = {}(s, p)?;\n    items.push(value);\n    p = next;\n",
                                self.fn_name(*child)
                            ));
                        }
                    }
                }
                match self.mode {
                    Mode::Acceptance => self.out.push_str("    Some(p)\n}\n\n"),
                    Mode::Shape => self.out.push_str("    Some((p, Value::Seq(items)))\n}\n\n"),
                }
                for child in atoms {
                    self.emit_atom(grammar, *child)?;
                }
                Ok(())
            }
            Atom::Alternative { atoms } => {
                let ret_type = match self.mode {
                    Mode::Acceptance => "usize",
                    Mode::Shape => "(usize, Value)",
                };
                let mut chain = String::new();
                for (index, child) in atoms.iter().enumerate() {
                    if index == 0 {
                        chain.push_str(&format!("{}(s, pos)", self.fn_name(*child)));
                    } else {
                        chain.push_str(&format!(".or_else(|| {}(s, pos))", self.fn_name(*child)));
                    }
                }
                self.out.push_str(&format!(
                    "fn {name}(s: &str, pos: usize) -> Option<{ret_type}> {{\n    {chain}\n}}\n\n"
                ));
                for child in atoms {
                    self.emit_atom(grammar, *child)?;
                }
                Ok(())
            }
            Atom::Repetition {
                atom,
                min,
                max,
                tag,
                ..
            } => {
                let ret_type = match self.mode {
                    Mode::Acceptance => "usize",
                    Mode::Shape => "(usize, Value)",
                };
                let max_check = match max {
                    Some(max) => format!("if count >= {max} {{ break; }}"),
                    None => String::new(),
                };
                if self.mode == Mode::Shape {
                    self.out.push_str(&format!(
                        "fn {name}(s: &str, pos: usize) -> Option<{ret_type}> {{\n\
                         \x20   let mut p = pos;\n\
                         \x20   let mut count = 0usize;\n\
                         \x20   let mut items: Vec<Value> = Vec::new();\n\
                         \x20   loop {{\n\
                         \x20       {max_check}\n\
                         \x20       match {}(s, p) {{\n\
                         \x20           Some((next, value)) => {{\n\
                         \x20               items.push(value);\n\
                         \x20               if next > p {{ p = next; count += 1; }} else {{ count += 1; break; }}\n\
                         \x20           }}\n\
                         \x20           None => break,\n\
                         \x20       }}\n\
                         \x20   }}\n\
                         \x20   if count >= {min} {{\n\
                         \x20       Some((p, Value::{}(items)))\n\
                         \x20   }} else {{\n\
                         \x20       None\n\
                         \x20   }}\n\
                         }}\n\n",
                        self.fn_name(*atom),
                        match tag {
                            RepetitionTag::Maybe => "Maybe",
                            RepetitionTag::Repetition => "Rep",
                        }
                    ));
                } else {
                    self.out.push_str(&format!(
                        "fn {name}(s: &str, pos: usize) -> Option<{ret_type}> {{\n\
                         \x20   let mut p = pos;\n\
                         \x20   let mut count = 0usize;\n\
                         \x20   loop {{\n\
                         \x20       {max_check}\n\
                         \x20       match {}(s, p) {{\n\
                         \x20           Some(next) if next > p => {{ p = next; count += 1; }}\n\
                         \x20           Some(next) => {{ p = next; count += 1; break; }}\n\
                         \x20           None => break,\n\
                         \x20       }}\n\
                         \x20   }}\n\
                         \x20   if count >= {min} {{ Some(p) }} else {{ None }}\n\
                         }}\n\n",
                        self.fn_name(*atom)
                    ));
                }
                self.emit_atom(grammar, *atom)
            }
            Atom::Named {
                name: capture,
                atom,
            } => {
                if self.mode == Mode::Shape {
                    self.out.push_str(&format!(
                        "fn {name}(s: &str, pos: usize) -> Option<(usize, Value)> {{\n\
                         \x20   let (end, inner) = {}(s, pos)?;\n\
                         \x20   Some((end, Value::Map(vec![(\"{}\".to_string(), inner)])))\n\
                         }}\n\n",
                        self.fn_name(*atom),
                        capture.escape_default()
                    ));
                } else {
                    self.out.push_str(&format!(
                        "fn {name}(s: &str, pos: usize) -> Option<usize> {{\n    {}(s, pos)\n}}\n\n",
                        self.fn_name(*atom)
                    ));
                }
                self.emit_atom(grammar, *atom)
            }
            Atom::Entity { atom } => {
                let ret_type = match self.mode {
                    Mode::Acceptance => "usize",
                    Mode::Shape => "(usize, Value)",
                };
                self.out.push_str(&format!(
                    "fn {name}(s: &str, pos: usize) -> Option<{ret_type}> {{\n    {}(s, pos)\n}}\n\n",
                    self.fn_name(*atom)
                ));
                self.emit_atom(grammar, *atom)
            }
            other => {
                let _ = other;
                Err(CodegenError::Unsupported(
                    "this atom kind (POC covers Str/Re-class/Sequence/Alternative/Repetition/Named/Entity)",
                ))
            }
        }
    }

    /// Emit a `Re` terminal whose pattern is one of the engine's
    /// character classes (the fast-path subset). Byte-level ASCII tests
    /// plus UTF-8 continuation handling, mirroring the walker's
    /// `parse_re` fast path exactly — complex regexes stay Unsupported.
    fn emit_re(&mut self, atom_id: usize, pattern: &str) -> Result<(), CodegenError> {
        let Some(class) = CharacterPattern::from_pattern(pattern) else {
            return Err(CodegenError::Unsupported(
                "regex pattern outside the character-class subset",
            ));
        };
        let name = self.fn_name(atom_id);
        if !self.helpers.contains("u8len") {
            self.helpers.insert("u8len");
            self.out.push_str(
                "fn utf8_len(b: u8) -> usize {\n\
                 \x20   if b < 0x80 { 1 } else if b >> 5 == 0b110 { 2 } else if b >> 4 == 0b1110 { 3 } else if b >> 3 == 0b11110 { 4 } else { 1 }\n\
                 }\n\n",
            );
        }
        self.out.push_str(&format!(
            "fn c{atom_id}(b: u8) -> bool {{\n    {}\n}}\n\n",
            class_test(class)
        ));
        // Negated and any-char classes consume a whole UTF-8 scalar (their
        // first byte matched) — utf8_len handles that for both modes.
        let ret = match self.mode {
            Mode::Acceptance => "Some(pos + utf8_len(byte))".to_string(),
            Mode::Shape => "Some((pos + utf8_len(byte), Value::Text(s[pos..pos + utf8_len(byte)].to_string())))"
                .to_string(),
        };
        self.out.push_str(&format!(
            "fn {name}(s: &str, pos: usize) -> Option<{}> {{\n\
             \x20   let b = s.as_bytes();\n\
             \x20   let byte = *b.get(pos)?;\n\
             \x20   if !c{atom_id}(byte) {{ return None; }}\n\
             \x20   {}\n\
             }}\n\n",
            match self.mode {
                Mode::Acceptance => "usize",
                Mode::Shape => "(usize, Value)",
            },
            ret
        ));
        Ok(())
    }
}

/// The byte test for one character class — the emission of the walker's
/// `CharacterPattern::matches`.
fn class_test(class: CharacterPattern) -> String {
    use CharacterPattern as C;
    let expression = match class {
        C::Digit => "(0x30..=0x39).contains(&b)".to_string(),
        C::NonDigit => "!(0x30..=0x39).contains(&b)".to_string(),
        C::Lower => "(0x61..=0x7a).contains(&b)".to_string(),
        C::Upper => "(0x41..=0x5a).contains(&b)".to_string(),
        C::Alpha => "(0x41..=0x5a).contains(&b) || (0x61..=0x7a).contains(&b)".to_string(),
        C::Alnum => {
            "(0x41..=0x5a).contains(&b) || (0x61..=0x7a).contains(&b) || (0x30..=0x39).contains(&b)"
                .to_string()
        }
        C::Word => {
            "(0x41..=0x5a).contains(&b) || (0x61..=0x7a).contains(&b) || (0x30..=0x39).contains(&b) || b == 0x5f"
                .to_string()
        }
        C::NonWord => {
            "!((0x41..=0x5a).contains(&b) || (0x61..=0x7a).contains(&b) || (0x30..=0x39).contains(&b) || b == 0x5f)"
                .to_string()
        }
        C::HexDigit => {
            "(0x30..=0x39).contains(&b) || (0x41..=0x46).contains(&b) || (0x61..=0x66).contains(&b)"
                .to_string()
        }
        C::Space => "b == 0x20 || (0x09..=0x0d).contains(&b)".to_string(),
        C::NonSpace => "!(b == 0x20 || (0x09..=0x0d).contains(&b))".to_string(),
        C::Blank => "b == 0x20 || b == 0x09".to_string(),
        C::Cntrl => "b < 0x20 || b == 0x7f".to_string(),
        C::Graph => "!(b < 0x20 || b == 0x7f) && b != 0x20".to_string(),
        C::Print => "!(b < 0x20 || b == 0x7f)".to_string(),
        C::Punct => {
            "(!(b < 0x20 || b == 0x7f) && b != 0x20) && !((0x41..=0x5a).contains(&b) || (0x61..=0x7a).contains(&b) || (0x30..=0x39).contains(&b))"
                .to_string()
        }
        C::Any => "true".to_string(),
    };
    format!("    {expression}")
}

